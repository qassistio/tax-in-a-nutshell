#!/usr/bin/env node
// Reads every server/db/migrations/NNNN_name.sql (drizzle-kit's default
// output — sequential-numbered .sql files alongside a meta/ folder of
// journal/snapshot JSON it uses to compute the next diff) and writes
// server/db/migrations/list.ts so Nitro's production build can import the
// SQL as plain TypeScript constants — reading files off disk at runtime
// (import.meta.glob, useStorage) isn't reliable inside Nitro's bundled
// serverless output, and won't work at all on Vercel where the deployed
// function bundle may not include arbitrary source files.
//
// Run automatically via: npm run db:generate  and  npm run build (prebuild)

import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const migrationsDir = resolve('server/db/migrations')
const outputFile = join(migrationsDir, 'list.ts')

const entries = readdirSync(migrationsDir, { withFileTypes: true })
  .filter(d => d.isFile() && d.name.endsWith('.sql'))
  .map(d => d.name)
  .sort()
  .map(fileName => ({
    name: fileName.replace(/\.sql$/, ''),
    sql: readFileSync(join(migrationsDir, fileName), 'utf-8')
  }))

const lines = [
  '// AUTO-GENERATED by scripts/gen-migration-list.mjs — do not edit by hand.',
  '// Re-run via `npm run db:generate` or `npm run build`.',
  '',
  'export const MIGRATIONS: ReadonlyArray<{ name: string; sql: string }> = [',
  ...entries.map(({ name, sql }) =>
    `  { name: ${JSON.stringify(name)}, sql: ${JSON.stringify(sql)} },`
  ),
  ']',
  ''
]

writeFileSync(outputFile, lines.join('\n'))
console.log(`[gen-migration-list] ${entries.length} migration(s) → list.ts`)
